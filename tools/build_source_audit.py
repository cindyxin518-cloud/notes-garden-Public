"""Generate the browser citation overlay without rewriting archived quote batches."""

import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
STATUSES = {"verified", "corroborated", "unverified", "misattributed", "access_limited"}
KINDS = {"excerpt", "editorial_translation", "paraphrase", "mixed", "quoted_in"}


def render(data):
    if data.get("schemaVersion") != 1 or not data.get("checkedDate") or not isinstance(data.get("records"), dict):
        raise ValueError("Invalid audit schema")
    for ident, record in data["records"].items():
        if not ident or record.get("status") not in STATUSES or record.get("textKind") not in KINDS:
            raise ValueError(f"Invalid audit record: {ident}")
        if not record.get("checkMethod") or "originalAttribution" not in record:
            raise ValueError(f"Missing audit evidence: {ident}")
        for url in [record.get("url", "")] + [item.get("url", "") for item in record.get("evidence", [])]:
            if url and (urlsplit(url).scheme not in {"https", "http"} or not urlsplit(url).netloc):
                raise ValueError(f"Invalid source URL: {ident}")
    payload = json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return "// Generated by tools/build_source_audit.py; edit data/source-audit.json.\nwindow.MINIGROW_SOURCE_AUDIT = " + payload + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((ROOT / "data/source-audit.json").read_text(encoding="utf-8"))
    content = render(data)
    output = ROOT / "source-audit.js"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != content:
            raise SystemExit("Source audit output differs; run tools/build_source_audit.py")
    else:
        output.write_text(content, encoding="utf-8")
    print(f"Source audit valid: {len(data['records'])} reviewed entries")


if __name__ == "__main__":
    main()
